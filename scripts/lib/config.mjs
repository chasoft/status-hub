import { parseJsonc } from "./jsonc.mjs";

const PLACEHOLDER_EMAIL = "you@example.com";

export function isPlaceholderDatabaseId(id) {
  return typeof id !== "string" || /^00000000-0000-0000-0000-00000000000[0-9a-f]$/i.test(id);
}

export function applySetup(config, setup) {
  const next = structuredClone(config);
  applyTarget(next, setup, {
    hosts: [setup.uiHost, setup.mcpHost],
    databaseName: setup.databaseName,
    databaseId: setup.databaseId,
    environmentFallback: "production",
  });
  if (setup.staging) {
    if (!next.env?.staging) throw new Error("wrangler config has no env.staging block");
    applyTarget(next.env.staging, setup, {
      hosts: [setup.stagingUiHost, setup.stagingMcpHost],
      databaseName: setup.stagingDatabaseName,
      databaseId: setup.stagingDatabaseId,
      environmentFallback: "staging",
    });
  }
  return next;
}

export function buildLocalConfig(baseText, setup) {
  return renderLocalConfig(applySetup(parseJsonc(baseText), setup), setup);
}

export function renderLocalConfig(config, setup) {
  const header = [
    "// Generated by `pnpm run setup`. Gitignored. Do not commit.",
    `// Timezone: ${setup.timezone} (${setup.tzOffsetMinutes} minutes east of UTC)`,
    "// Edit wrangler.jsonc for structural changes, then re-run `pnpm run setup`.",
    "",
  ].join("\n");
  return `${header}${JSON.stringify(config, null, 2)}\n`;
}

export function defaultsFromLocal(text) {
  const timezone = timezoneNote(text);
  return defaultsFromConfig(parseJsonc(text), timezone);
}

function timezoneNote(text) {
  const match = /^\/\/ Timezone: (.+) \((-?\d+) minutes east of UTC\)$/m.exec(text);
  return match ? match[1] : "";
}

function defaultsFromConfig(config, timezone) {
  const vars = config.vars ?? {};
  const stagingVars = config.env?.staging?.vars ?? {};
  const prodDb = findDb(config);
  const stagingDb = findDb(config.env?.staging ?? {});
  const member = firstRealPair(vars.UI_MEMBER_EMAILS);
  const leader = pairForEmail(vars.LEADERSHIP_AUTHORS, member?.email);
  return {
    orgName: vars.ORG_NAME ?? "",
    timezone: timezone || (vars.TZ_OFFSET_MINUTES != null ? String(vars.TZ_OFFSET_MINUTES) : ""),
    uiHost: vars.UI_HOST ?? "",
    mcpHost: vars.MCP_HOST ?? "",
    ownerIds: vars.OWNER_IDS ?? "",
    approverIds: vars.APPROVER_IDS ?? "",
    adminId: member?.mapped ?? "",
    adminEmail: member?.email ?? "",
    adminName: leader ?? "",
    databaseName: prodDb?.database_name ?? "status-hub",
    databaseId: prodDb?.database_id ?? "",
    stagingUiHost: stagingVars.UI_HOST ?? "",
    stagingMcpHost: stagingVars.MCP_HOST ?? "",
    stagingDatabaseName: stagingDb?.database_name ?? "status-hub-staging",
    stagingDatabaseId: stagingDb?.database_id ?? "",
    accessTeamDomain: vars.ACCESS_TEAM_DOMAIN ?? "",
    accessAud: vars.ACCESS_AUD ?? "",
    authMode: String(vars.AUTH_MODE ?? "").trim().toLowerCase() === "token" ? "token" : "access",
    stagingConfigured: Boolean(stagingDb && !isPlaceholderDatabaseId(stagingDb.database_id)),
  };
}

function applyTarget(target, setup, { hosts, databaseName, databaseId, environmentFallback }) {
  target.routes = hosts.map((pattern) => ({ pattern, custom_domain: true }));
  const vars = { ...(target.vars ?? {}) };
  if (!vars.ENVIRONMENT) vars.ENVIRONMENT = environmentFallback;
  vars.ORG_NAME = setup.orgName;
  vars.UI_HOST = hosts[0];
  vars.MCP_HOST = hosts[1];
  vars.OWNER_IDS = setup.ownerIds.join(",");
  vars.APPROVER_IDS = setup.approverIds.join(",");
  vars.TZ_OFFSET_MINUTES = String(setup.tzOffsetMinutes);
  vars.UI_ALLOWED_EMAILS = mergeCsv(vars.UI_ALLOWED_EMAILS, [setup.adminEmail]);
  vars.UI_MEMBER_EMAILS = mergePairs(vars.UI_MEMBER_EMAILS, setup.adminEmail, setup.adminId);
  vars.LEADERSHIP_AUTHORS = mergePairs(vars.LEADERSHIP_AUTHORS, setup.adminEmail, setup.adminName);
  if (setup.accessTeamDomain != null) vars.ACCESS_TEAM_DOMAIN = setup.accessTeamDomain;
  if (setup.accessAud != null) vars.ACCESS_AUD = setup.accessAud;
  vars.AUTH_MODE = setup.authMode === "token" ? "token" : "access";
  delete vars.AUTH_SESSION_SECRET;
  target.vars = vars;

  const databases = target.d1_databases ?? [];
  const index = databases.findIndex((db) => db.binding === "DB");
  const slot = index >= 0 ? index : 0;
  if (!databases[slot]) throw new Error("wrangler config has no d1_databases binding");
  databases[slot] = {
    ...databases[slot],
    database_name: databaseName,
    database_id: databaseId,
  };
  target.d1_databases = databases;
}

function mergeCsv(existing, additions) {
  const seen = new Set();
  const out = [];
  for (const part of String(existing ?? "").split(",")) {
    const item = part.trim().toLowerCase();
    if (!item || item === PLACEHOLDER_EMAIL || seen.has(item)) continue;
    seen.add(item);
    out.push(item);
  }
  for (const addition of additions) {
    const item = addition.toLowerCase();
    if (!item || seen.has(item)) continue;
    seen.add(item);
    out.push(item);
  }
  return out.join(",");
}

function mergePairs(existing, email, mapped) {
  const pairs = parsePairs(existing).filter((pair) => pair.email !== PLACEHOLDER_EMAIL && pair.email !== email);
  pairs.push({ email, mapped });
  return pairs.map((pair) => `${pair.email}=${pair.mapped}`).join(",");
}

function parsePairs(value) {
  const pairs = [];
  for (const part of String(value ?? "").split(",")) {
    const item = part.trim();
    if (!item) continue;
    const eq = item.indexOf("=");
    if (eq <= 0) continue;
    const email = item.slice(0, eq).trim().toLowerCase();
    const mapped = item.slice(eq + 1).trim();
    if (email && mapped) pairs.push({ email, mapped });
  }
  return pairs;
}

function firstRealPair(value) {
  return parsePairs(value).find((pair) => pair.email !== PLACEHOLDER_EMAIL) ?? null;
}

function pairForEmail(value, email) {
  if (!email) return "";
  return parsePairs(value).find((pair) => pair.email === email)?.mapped ?? "";
}

function findDb(target) {
  return (target.d1_databases ?? []).find((db) => db.binding === "DB") ?? target.d1_databases?.[0];
}
